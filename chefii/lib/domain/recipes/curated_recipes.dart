const _calc = NutritionCalculator();
const _guard = AllergenGuard();

/// Tags derived deterministically so they can never drift from the recipe.
List<String> derivedTags(Recipe r) {
  final tags = <String>{...r.tags};
  if (r.totalMinutes <= 15) tags.add('15-minute');
  if (r.nutritionPerServing[Nutrient.protein] >= 25) tags.add('high-protein');
  bool fits(String restriction) =>
      !_guard
          .checkRecipe(r, DietaryProfile(restrictions: [restriction], allergyStatus: DisclosureStatus.noneKnown),
              productAllergens: catalogAllergens)
          .isBlocked;
  if (fits('vegan')) {
    tags.add('vegan');
    tags.add('vegetarian');
  } else if (fits('vegetarian')) {
    tags.add('vegetarian');
  }
  return tags.toList()..sort();
}

Recipe _finish(Recipe r) {
  final withN = _calc.withNutrition(r);
  return Recipe(
    id: withN.id,
    title: withN.title,
    summary: withN.summary,
    cuisine: withN.cuisine,
    mealTypes: withN.mealTypes,
    servings: withN.servings,
    prepMinutes: withN.prepMinutes,
    cookMinutes: withN.cookMinutes,
    difficulty: withN.difficulty,
    ingredients: withN.ingredients,
    steps: withN.steps,
    origin: withN.origin,
    tags: derivedTags(withN),
    equipment: withN.equipment,
    nutritionPerServing: withN.nutritionPerServing,
    imageKey: withN.imageKey,
    storageNotes: withN.storageNotes,
  );
}

