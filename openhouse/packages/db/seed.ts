/**
 * Emits the catalog seed as SQL. The catalog lives in TypeScript because it is
 * code that other code depends on; the database needs it as rows, and hand-
 * maintaining both would guarantee they drift.
 *
 *   node packages/db/seed.ts > packages/db/seed/001_fact_catalog.sql
 */
import {
  CATALOG_VERSION, FACT_DEFINITIONS, QUESTION_TEMPLATES, toSeedRows,
} from '../fact-catalog/src/index.ts';

const lit = (value: unknown): string => {
  if (value === null || value === undefined) return 'null';
  if (typeof value === 'number') return String(value);
  if (typeof value === 'boolean') return String(value);
  return `'${String(value).replace(/'/g, "''")}'`;
};

const textArray = (values: string[]): string =>
  `ARRAY[${values.map(lit).join(', ')}]::text[]`;

const lines: string[] = [
  '-- Generated by packages/db/seed.ts — do not edit by hand.',
  `-- Catalog version ${CATALOG_VERSION}: ${FACT_DEFINITIONS.length} fact definitions, ` +
  `${QUESTION_TEMPLATES.length} question templates.`,
  '',
  'begin;',
  '',
];

for (const row of toSeedRows()) {
  lines.push(
    'insert into fact_definitions (key, label, section, category, data_type, unit,',
    '  enum_options, applies_when, default_visibility, is_disclosure, coverage_weight,',
    '  answers_questions, room_scoped, help_text, catalog_version) values (',
    `  ${lit(row.key)}, ${lit(row.label)}, ${lit(row.section)}, ${lit(row.category)},`,
    `  ${lit(row.data_type)}, ${lit(row.unit)},`,
    `  ${row.enum_options ? `${lit(row.enum_options)}::jsonb` : 'null'},`,
    `  ${lit(row.applies_when)}::jsonb, ${lit(row.default_visibility)},`,
    `  ${row.is_disclosure}, ${row.coverage_weight},`,
    `  ${textArray(row.answers_questions)}, ${row.room_scoped}, ${lit(row.help_text)},`,
    `  ${row.catalog_version})`,
    'on conflict (key) do update set',
    '  label = excluded.label, section = excluded.section, category = excluded.category,',
    '  data_type = excluded.data_type, unit = excluded.unit,',
    '  enum_options = excluded.enum_options, applies_when = excluded.applies_when,',
    '  default_visibility = excluded.default_visibility,',
    '  is_disclosure = excluded.is_disclosure, coverage_weight = excluded.coverage_weight,',
    '  answers_questions = excluded.answers_questions, room_scoped = excluded.room_scoped,',
    '  help_text = excluded.help_text, catalog_version = excluded.catalog_version;',
    '',
  );
}

for (const template of QUESTION_TEMPLATES) {
  lines.push(
    'insert into question_templates (question, normalized, fact_keys, category, frequency, is_seed)',
    `values (${lit(template.question)}, ${lit(template.normalized)},`,
    `  ${textArray(template.factKeys)}, ${lit(template.category)}, ${template.frequency}, true)`,
    'on conflict (normalized) do update set',
    '  fact_keys = excluded.fact_keys, frequency = excluded.frequency;',
    '',
  );
}

lines.push('commit;', '');
process.stdout.write(lines.join('\n'));
